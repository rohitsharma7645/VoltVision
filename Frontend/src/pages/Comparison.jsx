
import { useState } from "react";
import axios from "axios";

import {
  BarChart,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  ResponsiveContainer
} from "recharts";


function Comparison() {

  const [formData, setFormData] = useState({
    AT: "",
    V: "",
    AP: "",
    RH: ""
  });

  const [results, setResults] = useState([]);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);


  // Handle input changes
  const handleChange = (e) => {

    setFormData({
      ...formData,
      [e.target.name]: e.target.value
    });

  };


  // Get predictions from all models
  const handleSubmit = async (e) => {

    e.preventDefault();

    setLoading(true);
    setError("");
    setResults([]);

    try {

      const response = await axios.post(
        "http://127.0.0.1:8000/predict/all",
        {
          AT: Number(formData.AT),
          V: Number(formData.V),
          AP: Number(formData.AP),
          RH: Number(formData.RH)
        }
      );

      const data = Object.entries(
        response.data.predictions
      ).map(([model, prediction]) => ({
        model,
        prediction
      }));

      setResults(data);

    } catch (err) {

      setError("Unable to compare models. Please try again.");
      console.log(err);

    } finally {

      setLoading(false);

    }

  };


  return (

    <div className="comparison-page">

      <div className="comparison-header">

        <p className="small-heading">MODEL EVALUATION</p>

        <h1>Model Comparison</h1>

        <p>
          Compare energy predictions generated by
          different regression algorithms.
        </p>

      </div>


      {/* Input Form */}

      <div className="comparison-form">

        <h2>Enter Input Features</h2>

        <form onSubmit={handleSubmit}>

          <div>
            <label>Ambient Temperature (AT)</label>

            <input
              type="number"
              name="AT"
              placeholder="E.g.-25.0"
              value={formData.AT}
              onChange={handleChange}
              step="any"
              required
            />
          </div>


          <div>
            <label>Exhaust Vacuum (V)</label>

            <input
              type="number"
              name="V"
              placeholder="E.g.-60.0"
              value={formData.V}
              onChange={handleChange}
              step="any"
              required
            />
          </div>


          <div>
            <label>Ambient Pressure (AP)</label>

            <input
              type="number"
              name="AP"
              placeholder="E.g.-1010.5"
              value={formData.AP}
              onChange={handleChange}
              step="any"
              required
            />
          </div>


          <div>
            <label>Relative Humidity (RH)</label>

            <input
              type="number"
              name="RH"
              placeholder="E.g.-70.5"
              value={formData.RH}
              onChange={handleChange}
              step="any"
              required
            />
          </div>


          <button type="submit" disabled={loading}>
            {loading ? "Comparing..." : "Compare Models"}
          </button>

        </form>

        {error && <p className="error">{error}</p>}

      </div>


      {/* Prediction Results */}

      {results.length > 0 && (

        <>

          <div className="comparison-results">

            <h2>Prediction Results</h2>

            <div className="table-container">

              <table>

                <thead>
                  <tr>
                    <th>Model</th>
                    <th>Predicted Energy (MW)</th>
                  </tr>
                </thead>

                <tbody>

                  {results.map((item) => (

                    <tr key={item.model}>

                      <td>
                        {item.model.replaceAll("_", " ")}
                      </td>

                      <td>
                        {Number(item.prediction).toFixed(2)}
                      </td>

                    </tr>

                  ))}

                </tbody>

              </table>

            </div>

          </div>


          {/* Prediction Chart */}

          <div className="comparison-chart">

            <h2>Model Prediction Comparison</h2>

            <p>
              Comparison of predicted energy output
              across all seven models.
            </p>

            <ResponsiveContainer width="100%" height={350}>

              <BarChart data={results}>

                <CartesianGrid
                  strokeDasharray="3 3"
                  stroke="#D9DDCF"
                />

                <XAxis
                  dataKey="model"
                  tickFormatter={(value) =>
                    value.replaceAll("_", " ")
                  }
                  angle={-15}
                  textAnchor="end"
                  height={70}
                  tick={{ fill: "#34463A", fontSize: 11 }}
                />

                <YAxis
                  tick={{ fill: "#34463A" }}
                />

                <Tooltip />

                <Bar
                  dataKey="prediction"
                  fill="#91A994"
                  radius={[6, 6, 0, 0]}
                />

              </BarChart>

            </ResponsiveContainer>

          </div>

        </>

      )}

    </div>

  );

}

export default Comparison;
